/**
 * A bus (node) in the 7-bus microgrid topology.
 *
 * @property id          - Unique identifier, e.g. `"BUS-01"`
 * @property label       - Human-readable label shown in the topology SVG
 * @property x           - SVG x-coordinate in a 600×400 viewBox
 * @property y           - SVG y-coordinate in a 600×400 viewBox
 * @property lmp         - Locational Marginal Price in ₹/kWh
 * @property injectionMW - Net power injection in MW (positive = generation, negative = load)
 * @property type        - Asset class of the bus
 */
export interface Bus {
  /** Unique bus identifier, e.g. `"BUS-01"`. */
  id: string;
  /** Human-readable label displayed in the topology SVG. */
  label: string;
  /** SVG x-coordinate within a 600×400 viewBox. */
  x: number;
  /** SVG y-coordinate within a 600×400 viewBox. */
  y: number;
  /** Locational Marginal Price in ₹/kWh. */
  lmp: number;
  /** Net power injection in MW. Positive = generation; negative = load. */
  injectionMW: number;
  /** Asset class of the bus. */
  type: 'solar' | 'load' | 'storage' | 'slack';
  /** Live congestion status from the PTDF engine (OK / CONSTRAINED / BLOCKED). */
  status?: 'OK' | 'CONSTRAINED' | 'BLOCKED';
  /** LMP decomposition — energy component (₹/kWh). */
  energy?: number;
  /** LMP decomposition — marginal loss component (₹/kWh). */
  loss?: number;
  /** LMP decomposition — congestion (shadow cost) component (₹/kWh). */
  congestion?: number;
}

/**
 * A transmission line (edge) connecting two buses in the microgrid.
 *
 * Status thresholds:
 *  - `utilizationPct > 95`          → `'critical'`
 *  - `85 < utilizationPct <= 95`    → `'amber'`
 *  - otherwise                      → `'normal'`
 *
 * @property id             - Unique line identifier, e.g. `"LINE-01"`
 * @property from           - Source bus ID
 * @property to             - Destination bus ID
 * @property flowMW         - Current active power flow in MW
 * @property capacityMW     - Thermal rating (maximum flow) in MW
 * @property utilizationPct - |flowMW| / capacityMW × 100
 * @property status         - Congestion status based on utilization thresholds
 * @property ptdfRow        - Row of the PTDF matrix for this line (7 elements)
 */
export interface Line {
  /** Unique line identifier, e.g. `"LINE-01"`. */
  id: string;
  /** Source bus ID. */
  from: string;
  /** Destination bus ID. */
  to: string;
  /** Active power flow in MW. */
  flowMW: number;
  /** Thermal capacity (maximum allowable flow) in MW. */
  capacityMW: number;
  /** Utilization percentage: |flowMW| / capacityMW × 100. */
  utilizationPct: number;
  /**
   * Congestion status derived from `utilizationPct`.
   * - `'normal'`   : utilizationPct ≤ 85
   * - `'amber'`    : 85 < utilizationPct ≤ 95
   * - `'critical'` : utilizationPct > 95
   */
  status: 'normal' | 'amber' | 'critical';
  /** PTDF row vector for this line; one entry per bus (7 elements). */
  ptdfRow: number[];
  /** Shadow price μ_l of the thermal constraint (₹/kWh), 0 when slack. */
  shadowPrice?: number;
}

/**
 * Complete snapshot of the microgrid state: buses, lines, and the PTDF matrix.
 *
 * PTDF (Power Transfer Distribution Factor) matrix: shape [9 lines × 7 buses].
 * Element PTDF[l][b] = fraction of a 1 MW injection at bus b that flows on line l.
 *
 * @property buses - Array of 7 bus objects
 * @property lines - Array of 9 line objects
 * @property ptdf  - [9 × 7] PTDF matrix
 */
export interface GridData {
  /** Array of 7 bus objects (BUS-01 … BUS-07). */
  buses: Bus[];
  /** Array of 9 transmission lines. */
  lines: Line[];
  /**
   * Power Transfer Distribution Factor matrix.
   * Dimensions: [9 lines × 7 buses].
   * PTDF[l][b] = sensitivity of line l flow to a 1 MW injection shift at bus b.
   */
  ptdf: number[][];
}

