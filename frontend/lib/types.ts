/**
 * A single section within an article's body, used for structured rendering.
 *
 * @property heading - Section heading text
 * @property content - Prose content; may include inline LaTeX-style notation
 *                     surrounded by backticks, e.g. `δ_ask(q) = base − …`
 */
export interface ArticleSection {
  /** Section heading text. */
  heading: string;
  /**
   * Prose content for this section.
   * Inline math notation uses backtick delimiters, e.g. `σ²γ / (2kA)`.
   */
  content: string;
}

/**
 * A research article in the Sovereign-AMM knowledge base.
 *
 * Category → badge colour mapping (bijection):
 *  - `'QUANT RESEARCH'`   → `'emerald'`
 *  - `'HARDWARE PHYSICS'` → `'amber'`
 *  - `'GRID PHYSICS'`     → `'sky'`
 *  - `'WHITE PAPER'`      → `'slate'`
 *  - `'APPLIED CRYPTO'`   → `'violet'`
 *
 * @property slug        - URL-safe identifier, e.g. `"glft-vs-avellaneda-stoikov"`
 * @property title       - Display title
 * @property category    - Research category (drives badge colour)
 * @property badgeColor  - Tailwind colour token for the category badge
 * @property publishedAt - ISO 8601 date string, e.g. `"2024-01-15"`
 * @property readTime    - Estimated reading time in minutes
 * @property summary     - One-paragraph summary used on listing cards
 * @property body        - Ordered array of prose sections
 * @property pullQuote   - Highlighted pull-quote rendered in the article detail view
 */
export interface Article {
  /** URL-safe slug, unique across all articles. */
  slug: string;
  /** Display title of the article. */
  title: string;
  /**
   * Research category.
   * Determines the `badgeColor` via the category→colour bijection.
   */
  category:
    | 'QUANT RESEARCH'
    | 'HARDWARE PHYSICS'
    | 'GRID PHYSICS'
    | 'WHITE PAPER'
    | 'APPLIED CRYPTO';
  /**
   * Tailwind colour token for the category badge.
   * Must match the category→colour bijection exactly.
   */
  badgeColor: 'emerald' | 'amber' | 'sky' | 'slate' | 'violet';
  /** ISO 8601 publication date string, e.g. `"2024-01-15"`. */
  publishedAt: string;
  /** Estimated reading time in minutes (integer). */
  readTime: number;
  /** One-paragraph summary used on article listing cards. */
  summary: string;
  /** Ordered body sections with headings and prose content. */
  body: ArticleSection[];
  /** Pull-quote highlighted in the article detail view. */
  pullQuote: string;
}

