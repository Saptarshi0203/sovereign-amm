/**
 * One historical data point produced by `generateTimeseries()`.
 * 240 points are generated at module load time with 100 ms spacing.
 *
 * @property t     - Unix millisecond timestamp
 * @property price - Micro-price in ₹/kWh (Ornstein-Uhlenbeck process, μ=4.85)
 * @property soc   - State of Charge in percent [18, 92]
 * @property cDeg  - Rainflow marginal wear cost in ₹/kWh, clamped to [0.001, 0.08]
 */
export interface TimeseriesPoint {
  /** Unix millisecond timestamp; points are spaced 100 ms apart. */
  t: number;
  /**
   * Micro-price in ₹/kWh.
   * Follows an Ornstein-Uhlenbeck process: θ=0.7, μ=4.85, σ=0.06, dt=0.1.
   */
  price: number;
  /**
   * Battery state of charge in percent.
   * Bounded to [18, 92]; negatively correlated to price deviations from μ.
   */
  soc: number;
  /**
   * Rainflow marginal degradation cost in ₹/kWh.
   * C_deg = C_cap / (2 · N_cycles(d) · E_nom · η)
   * Rises on SoC reversals > 4%, decays 3 %/tick otherwise.
   * Clamped to [0.001, 0.08].
   */
  cDeg: number;
}

