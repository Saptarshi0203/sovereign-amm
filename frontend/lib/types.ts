/**
 * Result returned by `matchQuery(query)` after simulated 600 ms latency.
 *
 * When `isFallback` is `true`, no keyword group matched and a generic
 * fallback answer is used.
 *
 * @property answer             - Main answer paragraph shown to the user
 * @property sources            - List of source document titles or URLs
 * @property suggestedQuestions - Follow-up questions to show as chips
 * @property isFallback         - `true` when no keyword group matched
 */
export interface RagResult {
  /** Main answer paragraph rendered in the RAG copilot panel. */
  answer: string;
  /**
   * Source references for this answer (document titles or short URLs).
   * Rendered as a bulleted list below the answer.
   */
  sources: string[];
  /**
   * Follow-up question suggestions rendered as clickable chips.
   * Clicking a chip pre-fills the query input.
   */
  suggestedQuestions: string[];
  /**
   * `true` when no keyword group matched the query and the fallback
   * answer was used instead. Components may render a subtle indicator.
   */
  isFallback: boolean;
}

