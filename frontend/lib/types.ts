/**
 * A single price level in the L2 order book.
 *
 * @property px  - Price in ₹/kWh
 * @property sz  - Size (quantity) in kWh
 */
export interface Level {
  /** Price in ₹/kWh. */
  px: number;
  /** Size (quantity) in kWh. */
  sz: number;
}

/**
 * A snapshot of the L2 limit order book, containing 12 bid levels and 12 ask
 * levels generated by the GLFT market-making engine.
 *
 * Invariants:
 *  - `bids` is sorted by `px` descending (best bid first)
 *  - `asks` is sorted by `px` ascending  (best ask first)
 *  - `seq` increments monotonically on each call to `stepBook`
 *
 * @property bids - 12 bid levels, descending price
 * @property asks - 12 ask levels, ascending price
 * @property seq  - Monotone sequence counter; incremented by `stepBook`
 */
export interface OrderBook {
  /** 12 bid levels sorted by price descending. */
  bids: Level[];
  /** 12 ask levels sorted by price ascending. */
  asks: Level[];
  /** Monotone sequence counter, incremented on every `stepBook` call. */
  seq: number;
}

/**
 * A single time-and-sales trade record appended to the rolling 50-entry
 * trade tape in the market slice.
 *
 * @property id   - Deterministic trade ID derived from `book.seq`
 * @property ts   - Wall-clock timestamp in Unix milliseconds (Date.now())
 * @property side - Aggressor side: `'buy'` when OBI > 0, `'sell'` otherwise
 * @property px   - Execution price (micro-price at the tick) in ₹/kWh
 * @property sz   - Trade size in kWh
 */
export interface Trade {
  /** Deterministic trade ID, e.g. `"t-42"`. */
  id: string;
  /** Unix millisecond timestamp from `Date.now()`. */
  ts: number;
  /** Aggressor side: `'buy'` when OBI > 0, `'sell'` otherwise. */
  side: 'buy' | 'sell';
  /** Execution price in ₹/kWh (micro-price at tick time). */
  px: number;
  /** Trade size in kWh. */
  sz: number;
}

